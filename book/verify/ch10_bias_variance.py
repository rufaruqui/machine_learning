"""Chapter 10 --- numbers for evaluation, bias and variance.

Dataset T10: 50 points, x ~ Uniform(0, 3), y = sin(2x) + 0.5x + N(0, 0.25^2),
generated by numpy.random.default_rng(4) exactly as in the chapter's listing.
Split in order: 20 training, 15 validation, 15 test.  Polynomial features are
powers of (x - 1.5)/1.5, standardised on the training set.

Cost convention: J = (1/2m) sum (f - y)^2.  The bias-variance section uses
mean squared error without the 1/2, as stated in the text.

Run:  /tmp/mlenv/bin/python verify/ch10_bias_variance.py
"""

import numpy as np

np.set_printoptions(precision=4, suppress=True)

f_true = lambda x: np.sin(2 * x) + 0.5 * x
SIGMA = 0.25


def make_T10():
    rng = np.random.default_rng(4)
    x = rng.uniform(0, 3, 50)
    y = f_true(x) + rng.normal(0, SIGMA, 50)
    return x, y


def feats(x, d):
    s = (x - 1.5) / 1.5
    return np.vstack([s ** k for k in range(1, d + 1)]).T


def fit(x, y, d, lam=0.0):
    P = feats(x, d)
    mu, sd = P.mean(0), P.std(0)
    A = np.c_[np.ones(len(y)), (P - mu) / sd]
    R = lam * np.eye(d + 1)
    R[0, 0] = 0
    th = np.linalg.solve(A.T @ A + R, A.T @ y)
    return th, mu, sd, d


def predict(model, x):
    th, mu, sd, d = model
    return np.c_[np.ones(len(x)), (feats(x, d) - mu) / sd] @ th


J = lambda m, x, y: float(np.mean((predict(m, x) - y) ** 2) / 2)

x, y = make_T10()
xtr, ytr, xcv, ycv, xte, yte = x[:20], y[:20], x[20:35], y[20:35], x[35:], y[35:]

print("[T10] first five points:", [(round(a, 3), round(b, 3)) for a, b in zip(x[:5], y[:5])])
print(f"  noise floor sigma^2/2 = {SIGMA ** 2 / 2:.5f}")

print("\n[10.3] degree sweep: J_train, J_cv, J_test")
rows = []
for d in range(1, 11):
    m = fit(xtr, ytr, d)
    rows.append((d, J(m, xtr, ytr), J(m, xcv, ycv), J(m, xte, yte)))
    print(f"  d = {d:2d}:  {rows[-1][1]:.4f}  {rows[-1][2]:.4f}  {rows[-1][3]:.4f}")
dcv = min(rows, key=lambda r: r[2])
dte = min(rows, key=lambda r: r[3])
print(f"  chosen on validation: d = {dcv[0]} (J_cv {dcv[2]:.4f}), reported J_test {dcv[3]:.4f}")
print(f"  chosen on test (wrong): d = {dte[0]}, J_test {dte[3]:.4f}")

print("\n[10.4] 5-fold cross-validation on the 35 training+validation points")
x35, y35 = x[:35], y[:35]
perm = np.random.default_rng(10).permutation(35)
folds = np.array_split(perm, 5)
cvres = []
for d in range(1, 11):
    errs = []
    for k in range(5):
        va = folds[k]
        tr = np.concatenate([folds[j] for j in range(5) if j != k])
        m = fit(x35[tr], y35[tr], d)
        errs.append(J(m, x35[va], y35[va]))
    cvres.append((d, np.mean(errs), np.std(errs)))
    print(f"  d = {d:2d}:  mean {np.mean(errs):.4f}  sd {np.std(errs):.4f}  folds {np.round(errs, 4)}")
best = min(cvres, key=lambda r: r[1])
m = fit(x35, y35, best[0])
print(f"  chosen d = {best[0]}; refit on all 35, J_test = {J(m, xte, yte):.4f}")
print(f"  fold sizes: {[len(f) for f in folds]}")

print("\n[10.5] bias-variance decomposition by simulation (MSE, no 1/2)")
xg = np.linspace(0.25, 2.75, 51)       # evaluate inside the data range
S, M = 2000, 30                        # 2000 training sets of 30 points
for d in (1, 2, 3, 5, 7, 9):
    preds = np.empty((S, len(xg)))
    rng = np.random.default_rng(100 + d)
    for s in range(S):
        xs = rng.uniform(0, 3, M)
        ys = f_true(xs) + rng.normal(0, SIGMA, M)
        preds[s] = predict(fit(xs, ys, d), xg)
    mean_pred = preds.mean(0)
    bias2 = float(np.mean((mean_pred - f_true(xg)) ** 2))
    var = float(np.mean(preds.var(0)))
    # direct estimate of expected test MSE with fresh noise
    rng2 = np.random.default_rng(999)
    noise = rng2.normal(0, SIGMA, preds.shape)
    mse = float(np.mean((f_true(xg) + noise - preds) ** 2))
    print(f"  d = {d}:  bias^2 = {bias2:.4f}  variance = {var:.4f}  sigma^2 = {SIGMA ** 2:.4f}"
          f"  sum = {bias2 + var + SIGMA ** 2:.4f}  simulated MSE = {mse:.4f}")

print("\n[10.6] lambda sweep, degree 10")
for lam in [0, 1e-4, 1e-3, 1e-2, 0.1, 1, 10, 100]:
    m = fit(xtr, ytr, 10, lam)
    print(f"  lam = {lam:>6g}:  J_train {J(m, xtr, ytr):.4f}  J_cv {J(m, xcv, ycv):.4f}  J_test {J(m, xte, yte):.4f}")

print("\n[10.7] baseline arithmetic (illustrative speech example)")
for name, hum, tr, cv in [("A", 10.6, 10.8, 14.8), ("B", 10.6, 15.0, 15.5), ("C", 10.6, 15.0, 19.7)]:
    print(f"  case {name}: bias gap {tr - hum:.1f}, variance gap {cv - tr:.1f}")
print(f"  exercise: human 2.0, train 2.3, cv 7.1 -> bias gap {2.3 - 2.0:.1f}, variance gap {7.1 - 2.3:.1f}")

print("\n[10.8] learning curves (median of 100 random training sets; validation set of 200)")
rp = np.random.default_rng(40)
Xp = rp.uniform(0, 3, 600)
Yp = f_true(Xp) + rp.normal(0, SIGMA, 600)
Xv, Yv = Xp[400:], Yp[400:]
for d, sizes in [(1, [10, 12, 15, 20, 30, 50, 100, 200, 400]), (8, [20, 30, 50, 100, 200, 400])]:
    for mtr in sizes:
        tr, va = [], []
        for s in range(100):
            i = np.random.default_rng(1000 + s).choice(400, mtr, replace=False)
            mo = fit(Xp[i], Yp[i], d)
            tr.append(J(mo, Xp[i], Yp[i]))
            va.append(J(mo, Xv, Yv))
        print(f"  d = {d}, m = {mtr:3d}:  J_train {np.median(tr):.4f}  J_cv {np.median(va):.4f}")

print("\n[10.10] calibration: two classifiers with the same ranking")
sig = lambda z: 1 / (1 + np.exp(-z))
rc = np.random.default_rng(7)
xc = rc.uniform(-3, 3, 20000)
yc = (rc.uniform(size=20000) < sig(1.5 * xc)).astype(float)
pA = sig(1.5 * xc)            # the true probabilities: calibrated
pB = sig(4.5 * xc)            # same boundary, logits tripled: overconfident
edges = np.linspace(0, 1, 11)
for name, p in [("calibrated", pA), ("overconfident", pB)]:
    acc = np.mean((p >= 0.5) == yc)
    brier = np.mean((p - yc) ** 2)
    ll = -np.mean(yc * np.log(p) + (1 - yc) * np.log(1 - p))
    print(f"  {name}: accuracy {acc:.4f}, Brier {brier:.4f}, log loss {ll:.4f}")
    for lo, hi in zip(edges[:-1], edges[1:]):
        sel = (p >= lo) & (p < hi) if hi < 1 else (p >= lo)
        if sel.sum():
            print(f"     [{lo:.1f},{hi:.1f}): n = {sel.sum():5d}  mean predicted {p[sel].mean():.3f}"
                  f"  observed {yc[sel].mean():.3f}")
